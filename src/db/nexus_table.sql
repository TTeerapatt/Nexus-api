-- Bann Laundry schema (admin tables)
-- Soft delete: deleted_at IS NULL = แถวยังใช้
-- Query ปกติทุกตาราง: WHERE deleted_at IS NULL
-- Unique ของอีเมล / code ใช้ partial index

BEGIN;

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION set_updated_at() IS
  'อัปเดต updated_at อัตโนมัติทุกครั้งที่ UPDATE';

-- ---------------------------------------------------------------------------
-- admins
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS admins (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email          VARCHAR(255) NOT NULL,
  display_name   VARCHAR(255) NOT NULL,
  role           VARCHAR(32)  NOT NULL DEFAULT 'staff'
                   CHECK (role IN ('owner', 'admin', 'staff')),
  last_login_at  TIMESTAMPTZ,
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  deleted_at     TIMESTAMPTZ
);

COMMENT ON TABLE  admins IS 'พนักงาน / ผู้ดูแลระบบ (ข้อมูลโปรไฟล์)';
COMMENT ON COLUMN admins.id IS 'PK';
COMMENT ON COLUMN admins.email IS 'อีเมล — unique เฉพาะแถวที่ยังไม่ลบ';
COMMENT ON COLUMN admins.display_name IS 'ชื่อที่แสดง';
COMMENT ON COLUMN admins.role IS 'owner | admin | staff';
COMMENT ON COLUMN admins.last_login_at IS 'เวลา login ล่าสุด — อัปเดตตอน login สำเร็จ';
COMMENT ON COLUMN admins.created_at IS 'เวลาสร้าง';
COMMENT ON COLUMN admins.updated_at IS 'เวลาแก้ไขล่าสุด';
COMMENT ON COLUMN admins.deleted_at IS 'NULL = ยังใช้, มีค่า = soft delete';

CREATE UNIQUE INDEX IF NOT EXISTS admins_email_active_uidx
  ON admins (email)
  WHERE deleted_at IS NULL;

DROP TRIGGER IF EXISTS admins_set_updated_at ON admins;
CREATE TRIGGER admins_set_updated_at
  BEFORE UPDATE ON admins
  FOR EACH ROW
  EXECUTE FUNCTION set_updated_at();

